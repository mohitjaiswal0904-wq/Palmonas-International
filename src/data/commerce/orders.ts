function line(
  productId: string,
  quantity: number,
  overrides?: { size?: string; metalLabel?: string },
) {
  const p = productById(productId);
  if (!p) throw new Error(`Unknown product for demo order: ${productId}`);
  return {
    productId: p.id,
    name: p.name,
    category: p.category,
    slug: p.slug,
    metalLabel: overrides?.metalLabel ?? p.metals[0]?.label ?? "",
    size: overrides?.size ?? p.sizes[0],
    quantity,
    unitPrice: p.price,
    image: p.images[0].src,
    seed: p.images[0].seed,
    plate: p.images[0].plate,
  };
}

